from .nodes import Узел

РУС_МЕТОДЫ = {
    "вверх": "upper", "вниз": "lower", "заменить": "replace", "найти": "find",
    "убрать_пробелы": "strip", "соединить": "join", "начинается_с": "startswith",
    "кончается_на": "endswith", "добавить": "append", "разделить": "split",
}


class Генератор:
    def __init__(self):
        self.отступ = 0; self.строки = []; self.известные_имена = set()

    def собрать_имена(self, узел, имена):
        if узел is None: return
        if isinstance(узел, (list, tuple)):
            for u in узел: self.собрать_имена(u, имена)
            return
        if not isinstance(узел, Узел): return
        if узел.тип in ("Пусть", "Присвоить", "Константа"):
            имена.add(узел.имя)
        elif узел.тип == "ПрисвоитьЦель":
            if узел.цель.тип == "Имя": имена.add(узел.цель.имя)
        elif узел.тип == "ЦиклДиапазон":
            имена.add(узел.счетчик)
        elif узел.тип == "ЦиклКаждый":
            имена.add(узел.имя)
        elif узел.тип == "Функция":
            имена.add(узел.имя)
            for p in узел.параметры: имена.add(p)
        elif узел.тип == "Класс":
            имена.add(узел.имя); имена.add("само")
            for м in узел.методы:
                for p in м.параметры: имена.add(p)
        for значение in vars(узел).values():
            if isinstance(значение, (Узел, list, tuple)):
                self.собрать_имена(значение, имена)

    def сгенерировать(self, программа):
        self.известные_имена = set(); self.собрать_имена(программа, self.известные_имена)
        self.известные_имена |= {"пи", "е_число"}
        self.строки = []; self.source_map = {}; self.тек_строка = None
        for з in программа.заявления: self.заявление(з)
        return "\n".join(self.строки)

    def _добавить(self, текст):
        self.строки.append("    " * self.отступ + текст)
        if self.тек_строка: self.source_map[len(self.строки)] = self.тек_строка
    def тело(self, заявления):
        if not заявления: self._добавить("pass"); return
        for з in заявления: self.заявление(з)
    def заявление(self, з):
        self.тек_строка = getattr(з, 'строка', self.тек_строка)
        метод = getattr(self, f"з_{з.тип}", None)
        if метод is None: raise Exception(f"неизвестное заявление: {з.тип}")
        метод(з)
    def выражение(self, у):
        метод = getattr(self, f"в_{у.тип}", None)
        if метод is None: raise Exception(f"неизвестное выражение: {у.тип}")
        return метод(у)

    # заявления
    def з_Пусть(self, з): self._добавить(f"{з.имя} = {self.выражение(з.значение)}")
    def з_Присвоить(self, з): self._добавить(f"{з.имя} = {self.выражение(з.значение)}")
    def з_ПрисвоитьЦель(self, з): self._добавить(f"{self.выражение(з.цель)} = {self.выражение(з.значение)}")
    def з_ПрисвоитьИндекс(self, з): self._добавить(f"{з.имя}[{self.выражение(з.индекс)}] = {self.выражение(з.значение)}")
    def з_Глобально(self, з): self._добавить(f"global {', '.join(з.имена)}")
    def з_Печать(self, з):
        арг = []
        for a in з.аргументы:
            if a.тип == "Имя" and a.имя not in self.известные_имена:
                арг.append(repr(a.имя))
            else:
                арг.append(self.выражение(a))
        self._добавить(f"print({', '.join(арг)})")
    def з_Прервать(self, з): self._добавить("break")
    def з_Пропустить(self, з): self._добавить("continue")
    def з_Выход(self, з): self._добавить("raise SystemExit")
    def з_Добавить(self, з): self._добавить(f"{з.список}.append({self.выражение(з.значение)})")
    def з_Вернуть(self, з):
        self._добавить("return" if з.значение is None else f"return {self.выражение(з.значение)}")
    def з_ВыражениеЗаявление(self, з): self._добавить(self.выражение(з.выражение))
    def з_Если(self, з):
        первый = True
        for условие, тело in з.ветки:
            self._добавить(f"{'if' if первый else 'elif'} {self.выражение(условие)}:")
            self.отступ += 1; self.тело(тело); self.отступ -= 1; первый = False
        if з.иначе:
            self._добавить("else:"); self.отступ += 1; self.тело(з.иначе); self.отступ -= 1
    def з_ЦиклКаждый(self, з):
        self._добавить(f"for {з.имя} in {self.выражение(з.коллекция)}:")
        self.отступ += 1; self.тело(з.тело); self.отступ -= 1
    def з_Пока(self, з):
        self._добавить(f"while {self.выражение(з.условие)}:")
        self.отступ += 1; self.тело(з.тело); self.отступ -= 1
    def з_ЦиклРаз(self, з):
        self._добавить(f"for _ in range({self.выражение(з.количество)}):")
        self.отступ += 1; self.тело(з.тело); self.отступ -= 1
    def з_ЦиклДиапазон(self, з):
        self._добавить(f"for {з.счетчик} in range({self.выражение(з.начало)}, {self.выражение(з.конец)} + 1):")
        self.отступ += 1; self.тело(з.тело); self.отступ -= 1
    def з_Функция(self, з):
        self._добавить(f"def {з.имя}({', '.join(з.параметры)}):")
        self.отступ += 1; self.тело(з.тело); self.отступ -= 1
    def з_Класс(self, з):
        self._добавить(f"class {з.имя}:")
        self.отступ += 1
        if not з.методы: self._добавить("pass")
        for м in з.методы:
            self._добавить(f"def {м.имя}({', '.join(['self'] + м.параметры)}):")
            self.отступ += 1; self.тело(м.тело); self.отступ -= 1
        self.отступ -= 1
    def з_Константа(self, з): self._добавить(f"{з.имя} = {self.выражение(з.значение)}")
    def з_Проверить(self, з): self._добавить(f"assert {self.выражение(з.условие)}, 'проверка не прошла'")
    def з_Сопоставить(self, з):
        self._добавить(f"_соп = {self.выражение(з.значение)}")
        первый = True
        for шаблон, тело in з.случаи:
            self._добавить(f"{'if' if первый else 'elif'} _соп == {self.выражение(шаблон)}:")
            self.отступ += 1; self.тело(тело); self.отступ -= 1; первый = False
        if з.иначе:
            self._добавить("else:"); self.отступ += 1; self.тело(з.иначе); self.отступ -= 1
    def в_Ничто(self, у): return "None"
    def з_Попытка(self, з):
        self._добавить("try:"); self.отступ += 1; self.тело(з.тело); self.отступ -= 1
        self._добавить("except Exception:"); self.отступ += 1; self.тело(з.обработчик); self.отступ -= 1

    # выражения
    def в_Число(self, у): return repr(у.значение)
    def в_Строка(self, у): return repr(у.значение)
    def в_Булево(self, у): return "True" if у.значение else "False"
    def в_Имя(self, у):
        return {"само": "self", "пи": "math.pi", "е_число": "math.e"}.get(у.имя, у.имя)
    def в_Член(self, у):
        return f"{self.выражение(у.объект)}.{РУС_МЕТОДЫ.get(у.имя, у.имя)}"
    def в_Арифметика(self, у):
        if у.левый.тип == "Число" and у.правый.тип == "Число":
            try:
                return repr(eval(f"{у.левый.значение}{у.оп}{у.правый.значение}"))
            except Exception: pass
        return f"({self.выражение(у.левый)} {у.оп} {self.выражение(у.правый)})"
    def в_Логика(self, у):
        оп = "and" if у.оп == "и" else "or"
        return f"({self.выражение(у.левый)} {оп} {self.выражение(у.правый)})"
    def в_Не(self, у): return f"(not {self.выражение(у.операнд)})"
    def в_Минус(self, у): return f"(-{self.выражение(у.операнд)})"
    def в_Сравнение(self, у): return f"({self.выражение(у.левый)} {у.оп} {self.выражение(у.правый)})"
    def в_Кортеж(self, у): return "(" + ", ".join(self.выражение(e) for e in у.элементы) + ",)"
    def в_Список(self, у): return "[" + ", ".join(self.выражение(e) for e in у.элементы) + "]"
    def в_Словарь(self, у):
        return "{" + ", ".join(f"{self.выражение(k)}: {self.выражение(v)}" for k, v in у.пары) + "}"
    def в_Вызов(self, у):
        return f"{у.имя}({', '.join(self.выражение(a) for a in у.аргументы)})"
    def в_ВызовОбъект(self, у):
        return f"{self.выражение(у.объект)}({', '.join(self.выражение(a) for a in у.аргументы)})"
    def в_Индекс(self, у): return f"{self.выражение(у.объект)}[{self.выражение(у.индекс)}]"
