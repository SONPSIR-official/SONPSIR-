def _подсказка(слово):
    import difflib
    близ = difflib.get_close_matches(str(слово), sorted(КЛЮЧЕВЫЕ_СЛОВА), n=1, cutoff=0.5)
    return f" (возможно, вы имели в виду: {близ[0]})" if близ else ""

class Парсер:
    def __init__(self, токены):
        self.токены = токены; self.поз = 0

    def текущий(self): return self.токены[self.поз]
    def смотреть(self, смещение=1):
        i = self.поз + смещение
        return self.токены[i] if i < len(self.токены) else self.токены[-1]
    def следующий(self):
        т = self.токены[self.поз]
        if self.поз < len(self.токены) - 1: self.поз += 1
        return т
    def ждать(self, тип, значение=None):
        т = self.текущий()
        if т.тип != тип or (значение is not None and т.значение != значение):
            ожидал = значение if значение is not None else тип
            raise ОшибкаПарсера(f"ожидал {ожидал!r}, а получил {т.значение!r}", т.строка, т.позиция)
        return self.следующий()
    def это_ключ(self, *значения):
        т = self.текущий(); return т.тип == КЛЮЧ and т.значение in значения
    def пропустить_концы_строк(self):
        while self.текущий().тип == КОНЕЦ_СТРОКИ: self.следующий()
    def конец_строки_опц(self):
        while self.текущий().тип == КОНЕЦ_СТРОКИ: self.следующий()

    def разобрать(self):
        self.пропустить_концы_строк(); заявления = []
        while self.текущий().тип != КОНЕЦ_ФАЙЛА:
            старт = self.текущий().строка
            уз = self.заявление()
            if not hasattr(уз, 'строка'): уз.строка = старт
            заявления.append(уз); self.пропустить_концы_строк()
        return Узел("Программа", заявления=заявления)

    def блок_до(self, терминаторы):
        заявления = []
        while True:
            self.пропустить_концы_строк(); т = self.текущий()
            if т.тип == КОНЕЦ_ФАЙЛА:
                raise ОшибкаПарсера("файл кончился, а блок не закрыт", т.строка, т.позиция)
            if т.тип == КЛЮЧ and т.значение in терминаторы: break
            старт = self.текущий().строка
            уз = self.заявление()
            if not hasattr(уз, 'строка'): уз.строка = старт
            заявления.append(уз)
        return заявления

    # ---------- заявления ----------
    def заявление(self):
        т = self.текущий()
        if т.тип == КЛЮЧ:
            з = т.значение
            if з == "пусть": return self.пусть()
            if з == "если": return self.если()
            if з == "пока": return self.пока()
            if з == "повторять": return self.повторять()
            if з == "ДЛЯ_КАЖДОГО": return self.для_каждого()
            if з == "сопоставить": return self.сопоставить()
            if з == "константа": return self.константа()
            if з == "проверить": return self.проверить_заявление()
            if з == "функция": return self.функция()
            if з == "вернуть": return self.вернуть()
            if з == "ПЕЧАТЬ": return self.печать()
            if з == "попробовать": return self.попробовать()
            if з == "ДОБАВИТЬ_В": return self.добавить()
            if з == "класс": return self.класс()
            if з == "глобально": return self.глобально()
            if з in ("подключить", "использовать"): return self.подключить()
            if з == "ПРЕРВАТЬ": self.следующий(); self.конец_строки_опц(); return Узел("Прервать")
            if з == "ПРОПУСТИТЬ": self.следующий(); self.конец_строки_опц(); return Узел("Пропустить")
            if з == "выход": self.следующий(); self.конец_строки_опц(); return Узел("Выход")
        if т.тип == ИМЯ:
            старт = self.поз
            цель_узел = self.цель()
            if self.текущий().тип == ОПЕРАТОР and self.текущий().значение == "=":
                self.следующий(); значение = self.выражение(); self.конец_строки_опц()
                return Узел("ПрисвоитьЦель", цель=цель_узел, значение=значение)
            self.поз = старт
        выраж = self.выражение(); self.конец_строки_опц()
        return Узел("ВыражениеЗаявление", выражение=выраж)

    def цель(self):
        имя = self.ждать(ИМЯ).значение
        узел = Узел("Имя", имя=имя)
        while True:
            т = self.текущий()
            if т.тип == ЗНАК and т.значение == ".":
                self.следующий(); узел = Узел("Член", объект=узел, имя=self.ждать(ИМЯ).значение)
            elif т.тип == ЗНАК and т.значение == "[":
                self.следующий(); индекс = self.выражение(); self.ждать(ЗНАК, "]")
                узел = Узел("Индекс", объект=узел, индекс=индекс)
            else:
                break
        return узел

    def пусть(self):
        self.ждать(КЛЮЧ, "пусть"); имя = self.ждать(ИМЯ).значение
        self.ждать(ОПЕРАТОР, "="); значение = self.выражение(); self.конец_строки_опц()
        return Узел("Пусть", имя=имя, значение=значение)

    def печать(self):
        self.ждать(КЛЮЧ, "ПЕЧАТЬ"); self.ждать(ЗНАК, "(")
        аргументы = self.список_аргументов(); self.ждать(ЗНАК, ")"); self.конец_строки_опц()
        return Узел("Печать", аргументы=аргументы)

    def если(self):
        self.ждать(КЛЮЧ, "если"); условие = self.выражение(); self.ждать(КЛЮЧ, "то")
        self.пропустить_концы_строк()
        тело = self.блок_до(("КОНЕЦ_ЕСЛИ", "иначе", "ИНАЧЕ_ЕСЛИ"))
        ветки = [(условие, тело)]
        while self.это_ключ("ИНАЧЕ_ЕСЛИ"):
            self.следующий(); у = self.выражение(); self.ждать(КЛЮЧ, "то")
            self.пропустить_концы_строк()
            ветки.append((у, self.блок_до(("КОНЕЦ_ЕСЛИ", "иначе", "ИНАЧЕ_ЕСЛИ"))))
        тело_иначе = []
        if self.это_ключ("иначе"):
            self.следующий(); self.пропустить_концы_строк()
            тело_иначе = self.блок_до(("КОНЕЦ_ЕСЛИ",))
        self.ждать(КЛЮЧ, "КОНЕЦ_ЕСЛИ"); self.конец_строки_опц()
        return Узел("Если", ветки=ветки, иначе=тело_иначе)

    def пока(self):
        self.ждать(КЛЮЧ, "пока"); условие = self.выражение()
        if self.это_ключ("делать"): self.следующий()
        self.пропустить_концы_строк(); тело = self.блок_до(("КОНЕЦ_ЦИКЛА",))
        self.ждать(КЛЮЧ, "КОНЕЦ_ЦИКЛА"); self.конец_строки_опц()
        return Узел("Пока", условие=условие, тело=тело)

    def повторять(self):
        self.ждать(КЛЮЧ, "повторять")
        if self.текущий().тип == ИМЯ and self.смотреть(1).тип == КЛЮЧ and self.смотреть(1).значение == "от":
            счетчик = self.ждать(ИМЯ).значение; self.ждать(КЛЮЧ, "от")
            начало = self.выражение(); self.ждать(КЛЮЧ, "до"); конец = self.выражение()
            self.пропустить_концы_строк(); тело = self.блок_до(("КОНЕЦ_ЦИКЛА",))
            self.ждать(КЛЮЧ, "КОНЕЦ_ЦИКЛА"); self.конец_строки_опц()
            return Узел("ЦиклДиапазон", счетчик=счетчик, начало=начало, конец=конец, тело=тело)
        количество = self.выражение()
        if self.это_ключ("раз", "раза"): self.следующий()
        self.пропустить_концы_строк(); тело = self.блок_до(("КОНЕЦ_ЦИКЛА",))
        self.ждать(КЛЮЧ, "КОНЕЦ_ЦИКЛА"); self.конец_строки_опц()
        return Узел("ЦиклРаз", количество=количество, тело=тело)

    def для_каждого(self):
        self.ждать(КЛЮЧ, "ДЛЯ_КАЖДОГО"); имя = self.ждать(ИМЯ).значение
        self.ждать(КЛЮЧ, "из"); коллекция = self.выражение()
        self.пропустить_концы_строк(); тело = self.блок_до(("КОНЕЦ_ЦИКЛА",))
        self.ждать(КЛЮЧ, "КОНЕЦ_ЦИКЛА"); self.конец_строки_опц()
        return Узел("ЦиклКаждый", имя=имя, коллекция=коллекция, тело=тело)

    def функция(self):
        self.ждать(КЛЮЧ, "функция"); имя = self.ждать(ИМЯ).значение
        параметры = self.параметры()
        self.пропустить_концы_строк(); тело = self.блок_до(("КОНЕЦ_ФУНКЦИИ",))
        self.ждать(КЛЮЧ, "КОНЕЦ_ФУНКЦИИ"); self.конец_строки_опц()
        return Узел("Функция", имя=имя, параметры=параметры, тело=тело)

    def параметры(self):
        параметры = []
        if self.текущий().тип == ЗНАК and self.текущий().значение == "(":
            self.следующий()
            if not (self.текущий().тип == ЗНАК and self.текущий().значение == ")"):
                параметры.append(self.ждать(ИМЯ).значение)
                while self.текущий().тип == ЗНАК and self.текущий().значение == ",":
                    self.следующий(); параметры.append(self.ждать(ИМЯ).значение)
            self.ждать(ЗНАК, ")")
        return параметры

    def класс(self):
        self.ждать(КЛЮЧ, "класс"); имя = self.ждать(ИМЯ).значение
        self.пропустить_концы_строк(); методы = []
        while not self.это_ключ("КОНЕЦ_КЛАССА"):
            if self.текущий().тип == КОНЕЦ_ФАЙЛА:
                raise ОшибкаПарсера("класс не закрыт", self.текущий().строка, self.текущий().позиция)
            методы.append(self.метод()); self.пропустить_концы_строк()
        self.ждать(КЛЮЧ, "КОНЕЦ_КЛАССА"); self.конец_строки_опц()
        return Узел("Класс", имя=имя, методы=методы)

    def метод(self):
        self.ждать(КЛЮЧ, "метод"); имя = self.ждать(ИМЯ).значение
        параметры = self.параметры()
        self.пропустить_концы_строк(); тело = self.блок_до(("КОНЕЦ_МЕТОДА",))
        self.ждать(КЛЮЧ, "КОНЕЦ_МЕТОДА"); self.конец_строки_опц()
        питон_имя = "__init__" if имя == "создать" else имя
        return Узел("Метод", имя=питон_имя, параметры=параметры, тело=тело)

    def константа(self):
        self.ждать(КЛЮЧ, "константа"); имя = self.ждать(ИМЯ).значение
        self.ждать(ОПЕРАТОР, "="); значение = self.выражение(); self.конец_строки_опц()
        return Узел("Константа", имя=имя, значение=значение)
    def проверить_заявление(self):
        self.ждать(КЛЮЧ, "проверить"); условие = self.выражение(); self.конец_строки_опц()
        return Узел("Проверить", условие=условие)
    def сопоставить(self):
        self.ждать(КЛЮЧ, "сопоставить"); значение = self.выражение()
        self.пропустить_концы_строк(); случаи = []; иначе_тело = []
        while not self.это_ключ("КОНЕЦ_СОПОСТАВЛЕНИЯ"):
            if self.текущий().тип == КОНЕЦ_ФАЙЛА:
                raise ОшибкаПарсера("сопоставление не закрыто", self.текущий().строка, self.текущий().позиция)
            if self.это_ключ("случай"):
                self.следующий(); шаблон = self.выражение()
                if self.это_ключ("то"): self.следующий()
                self.пропустить_концы_строк()
                случаи.append((шаблон, self.блок_до(("случай", "иначе", "КОНЕЦ_СОПОСТАВЛЕНИЯ"))))
            elif self.это_ключ("иначе"):
                self.следующий()
                if self.это_ключ("то"): self.следующий()
                self.пропустить_концы_строк()
                иначе_тело = self.блок_до(("КОНЕЦ_СОПОСТАВЛЕНИЯ",))
            else:
                raise ОшибкаПарсера("ожидался случай или иначе", self.текущий().строка, self.текущий().позиция)
        self.ждать(КЛЮЧ, "КОНЕЦ_СОПОСТАВЛЕНИЯ"); self.конец_строки_опц()
        return Узел("Сопоставить", значение=значение, случаи=случаи, иначе=иначе_тело)
    def глобально(self):
        self.ждать(КЛЮЧ, "глобально"); имена = [self.ждать(ИМЯ).значение]
        while self.текущий().тип == ЗНАК and self.текущий().значение == ",":
            self.следующий(); имена.append(self.ждать(ИМЯ).значение)
        self.конец_строки_опц()
        return Узел("Глобально", имена=имена)

    def вернуть(self):
        self.ждать(КЛЮЧ, "вернуть"); значение = None; т = self.текущий()
        if т.тип not in (КОНЕЦ_СТРОКИ, КОНЕЦ_ФАЙЛА) and not (т.тип == КЛЮЧ and т.значение == "КОНЕЦ_ФУНКЦИИ"):
            значение = self.выражение()
        self.конец_строки_опц()
        return Узел("Вернуть", значение=значение)

    def попробовать(self):
        self.ждать(КЛЮЧ, "попробовать"); self.пропустить_концы_строк()
        тело = self.блок_до(("ПЕРЕХВАТИТЬ",)); self.ждать(КЛЮЧ, "ПЕРЕХВАТИТЬ")
        self.пропустить_концы_строк(); обработчик = self.блок_до(("КОНЕЦ_ПОПЫТКИ",))
        self.ждать(КЛЮЧ, "КОНЕЦ_ПОПЫТКИ"); self.конец_строки_опц()
        return Узел("Попытка", тело=тело, обработчик=обработчик)

    def добавить(self):
        self.ждать(КЛЮЧ, "ДОБАВИТЬ_В"); имя = self.ждать(ИМЯ).значение
        self.ждать(ЗНАК, "("); значение = self.выражение(); self.ждать(ЗНАК, ")"); self.конец_строки_опц()
        return Узел("Добавить", список=имя, значение=значение)

    def подключить(self):
        self.следующий(); т = self.текущий()
        if т.тип in (СТРОКА, ИМЯ):
            путь = т.значение; self.следующий()
        else:
            raise ОшибкаПарсера("ожидалось имя файла", т.строка, т.позиция)
        self.конец_строки_опц()
        return Узел("Подключить", путь=путь)

    # ---------- выражения ----------
    def выражение(self): return self.или_уровень()
    def или_уровень(self):
        лев = self.и_уровень()
        while self.это_ключ("или"):
            self.следующий(); лев = Узел("Логика", оп="или", левый=лев, правый=self.и_уровень())
        return лев
    def и_уровень(self):
        лев = self.не_уровень()
        while self.это_ключ("и"):
            self.следующий(); лев = Узел("Логика", оп="и", левый=лев, правый=self.не_уровень())
        return лев
    def не_уровень(self):
        if self.это_ключ("не"):
            self.следующий(); return Узел("Не", операнд=self.не_уровень())
        return self.сравнение()
    def сравнение(self):
        лев = self.сложение()
        while True:
            if self.это_ключ("в"):
                self.следующий(); лев = Узел("Сравнение", оп="in", левый=лев, правый=self.сложение())
            elif self.это_ключ("НЕ_В"):
                self.следующий(); лев = Узел("Сравнение", оп="not in", левый=лев, правый=self.сложение())
            elif self.текущий().тип == ОПЕРАТОР and self.текущий().значение in ("==", "!=", "<", ">", "<=", ">="):
                оп = self.следующий().значение; лев = Узел("Сравнение", оп=оп, левый=лев, правый=self.сложение())
            else:
                break
        return лев
    def сложение(self):
        лев = self.умножение()
        while self.текущий().тип == ОПЕРАТОР and self.текущий().значение in ("+", "-"):
            оп = self.следующий().значение; лев = Узел("Арифметика", оп=оп, левый=лев, правый=self.умножение())
        return лев
    def умножение(self):
        лев = self.унарный()
        while self.текущий().тип == ОПЕРАТОР and self.текущий().значение in ("*", "/", "%", "//"):
            оп = self.следующий().значение; лев = Узел("Арифметика", оп=оп, левый=лев, правый=self.унарный())
        return лев
    def унарный(self):
        if self.текущий().тип == ОПЕРАТОР and self.текущий().значение == "-":
            self.следующий(); return Узел("Минус", операнд=self.унарный())
        return self.степень()
    def степень(self):
        основание = self.первичное()
        if self.текущий().тип == ОПЕРАТОР and self.текущий().значение == "**":
            self.следующий(); return Узел("Арифметика", оп="**", левый=основание, правый=self.унарный())
        return основание

    def первичное(self):
        т = self.текущий()
        if т.тип == ЧИСЛО: self.следующий(); return self.постфикс(Узел("Число", значение=т.значение))
        if т.тип == СТРОКА: self.следующий(); return self.постфикс(Узел("Строка", значение=т.значение))
        if т.тип == КЛЮЧ and т.значение == "истина": self.следующий(); return self.постфикс(Узел("Булево", значение=True))
        if т.тип == КЛЮЧ and т.значение == "ложь": self.следующий(); return self.постфикс(Узел("Булево", значение=False))
        if т.тип == КЛЮЧ and т.значение == "ничто": self.следующий(); return self.постфикс(Узел("Ничто"))
        if т.тип == КЛЮЧ and т.значение in ("пи", "е_число"):
            self.следующий(); return self.постфикс(Узел("Имя", имя=т.значение))
        if т.тип == ИМЯ:
            self.следующий()
            у = Узел("Имя", имя=т.значение); у.строка = т.строка
            return self.постфикс(у)
        if т.тип == ЗНАК and т.значение == "(":
            self.следующий(); выраж = self.выражение(); self.ждать(ЗНАК, ")"); return self.постфикс(выраж)
        if т.тип == ЗНАК and т.значение == "[": return self.постфикс(self.список())
        if т.тип == ЗНАК and т.значение == "{": return self.постфикс(self.словарь())
        if т.тип == КЛЮЧ and (т.значение in ПИТОН_ИМЕНА or т.значение.isupper()): return self.постфикс(self.встроенный_вызов())
        raise ОшибкаПарсера(f"не понял {т.значение!r}{_подсказка(т.значение)}", т.строка, т.позиция)

    def встроенный_вызов(self):
        т = self.следующий(); имя = т.значение
        if имя == "СЛУЧАЙНОЕ_ОТ":
            низ = self.выражение(); self.ждать(КЛЮЧ, "до"); верх = self.выражение()
            return Узел("Вызов", имя="random.randint", аргументы=[низ, верх])
        аргументы = []
        if self.текущий().тип == ЗНАК and self.текущий().значение == "(":
            self.следующий(); аргументы = self.список_аргументов(); self.ждать(ЗНАК, ")")
        return Узел("Вызов", имя=ПИТОН_ИМЕНА.get(имя, имя.lower()), аргументы=аргументы)

    def постфикс(self, узел):
        while True:
            т = self.текущий()
            if т.тип == ЗНАК and т.значение == "(":
                self.следующий(); аргументы = self.список_аргументов(); self.ждать(ЗНАК, ")")
                узел = Узел("ВызовОбъект", объект=узел, аргументы=аргументы)
            elif т.тип == ЗНАК and т.значение == "[":
                self.следующий(); индекс = self.выражение(); self.ждать(ЗНАК, "]")
                узел = Узел("Индекс", объект=узел, индекс=индекс)
            elif т.тип == ЗНАК and т.значение == ".":
                self.следующий(); узел = Узел("Член", объект=узел, имя=self.ждать(ИМЯ).значение)
            else:
                break
        return узел

    def список_аргументов(self):
        аргументы = []
        if self.текущий().тип == ЗНАК and self.текущий().значение == ")": return аргументы
        аргументы.append(self.выражение())
        while self.текущий().тип == ЗНАК and self.текущий().значение == ",":
            self.следующий(); аргументы.append(self.выражение())
        return аргументы

    def список(self):
        self.ждать(ЗНАК, "["); элементы = []
        if not (self.текущий().тип == ЗНАК and self.текущий().значение == "]"):
            элементы.append(self.выражение())
            while self.текущий().тип == ЗНАК and self.текущий().значение == ",":
                self.следующий()
                if self.текущий().тип == ЗНАК and self.текущий().значение == "]": break
                элементы.append(self.выражение())
        self.ждать(ЗНАК, "]"); return Узел("Список", элементы=элементы)

    def словарь(self):
        self.ждать(ЗНАК, "{"); пары = []
        if not (self.текущий().тип == ЗНАК and self.текущий().значение == "}"):
            while True:
                ключ = self.выражение(); self.ждать(ЗНАК, ":"); пары.append((ключ, self.выражение()))
                if self.текущий().тип == ЗНАК and self.текущий().значение == ",":
                    self.следующий()
                    if self.текущий().тип == ЗНАК and self.текущий().значение == "}": break
                else:
                    break
        self.ждать(ЗНАК, "}"); return Узел("Словарь", пары=пары)
