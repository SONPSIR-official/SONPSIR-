ОПЕРАТОРЫ = ["**", "//", "==", "!=", "<=", ">=",
             "+", "-", "*", "/", "%", "<", ">", "="]
ЗНАКИ = set("()[]{},:.")


def нормализовать(код):
    правила = sorted(НОРМАЛИЗАЦИЯ, key=lambda x: -len(x[0]))
    образец = re.compile(r'("[^"\n]*"|\'[^\'\n]*\'|#[^\n]*)')
    части = образец.split(код)
    for i in range(0, len(части), 2):
        for рус, внутр in правила:
            части[i] = re.sub(r'(?<!\w)' + рус + r'(?!\w)', внутр, части[i])
    return "".join(части)


class Токен:
    def __init__(self, тип, значение, строка, позиция):
        self.тип = тип; self.значение = значение
        self.строка = строка; self.позиция = позиция
    def __repr__(self):
        return f"Токен({self.тип}, {self.значение!r}, стр {self.строка})"


class Лексер:
    def __init__(self, код):
        self.код = код; self.поз = 0; self.строка = 1

    def разобрать(self):
        токены = []; код = self.код; n = len(код)
        while self.поз < n:
            c = код[self.поз]
            if c == "\n":
                токены.append(Токен(КОНЕЦ_СТРОКИ, "\n", self.строка, self.поз)); self.строка += 1; self.поз += 1; continue
            if c in " \t\r": self.поз += 1; continue
            if c == "#":
                while self.поз < n and код[self.поз] != "\n": self.поз += 1
                continue
            if c in "\"'": токены.append(self._строка()); continue
            if c.isdigit(): токены.append(self._число()); continue
            if c.isalpha() or c == "_": токены.append(self._имя()); continue
            совпало = False
            for оп in ОПЕРАТОРЫ:
                if код.startswith(оп, self.поз):
                    токены.append(Токен(ОПЕРАТОР, оп, self.строка, self.поз)); self.поз += len(оп); совпало = True; break
            if совпало: continue
            if c in ЗНАКИ:
                токены.append(Токен(ЗНАК, c, self.строка, self.поз)); self.поз += 1; continue
            raise ОшибкаЛексера(f"неизвестный символ {c!r}", self.строка, self.поз)
        токены.append(Токен(КОНЕЦ_ФАЙЛА, "", self.строка, self.поз))
        return токены

    def _строка(self):
        кавычка = self.код[self.поз]; старт = self.поз; self.поз += 1; буфер = []
        while self.поз < len(self.код):
            c = self.код[self.поз]
            if c == "\\" and self.поз + 1 < len(self.код):
                буфер.append(c); буфер.append(self.код[self.поз + 1]); self.поз += 2; continue
            if c == кавычка:
                self.поз += 1; return Токен(СТРОКА, "".join(буфер), self.строка, старт)
            if c == "\n": raise ОшибкаЛексера("незакрытая строка", self.строка, старт)
            буфер.append(c); self.поз += 1
        raise ОшибкаЛексера("незакрытая строка", self.строка, старт)

    def _число(self):
        старт = self.поз
        while self.поз < len(self.код) and (self.код[self.поз].isdigit() or self.код[self.поз] == "."):
            self.поз += 1
        текст = self.код[старт:self.поз]
        return Токен(ЧИСЛО, float(текст) if "." in текст else int(текст), self.строка, старт)

    def _имя(self):
        старт = self.поз
        while self.поз < len(self.код) and (self.код[self.поз].isalnum() or self.код[self.поз] == "_"):
            self.поз += 1
        текст = self.код[старт:self.поз]
        if текст in КЛЮЧЕВЫЕ_СЛОВА or текст in ПИТОН_ИМЕНА_ДОП or текст.isupper(): return Токен(КЛЮЧ, текст, self.строка, старт)
        return Токен(ИМЯ, текст, self.строка, старт)
