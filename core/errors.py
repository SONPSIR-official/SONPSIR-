# Ошибки SONPSIR — с номером строки, чтобы было понятно, где упало

class ОшибкаСонпсир(Exception):
    def __init__(self, сообщение, строка=None, позиция=None):
        self.строка = строка
        self.позиция = позиция
        if строка is not None:
            сообщение = f"[строка {строка}] {сообщение}"
        super().__init__(сообщение)

class ОшибкаЛексера(ОшибкаСонпсир):
    pass

class ОшибкаПарсера(ОшибкаСонпсир):
    pass

class ОшибкаТрансляции(ОшибкаСонпсир):
    pass
